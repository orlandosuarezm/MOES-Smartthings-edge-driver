local RCON = {0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36}

-- Multiplicación en GF(2^8) módulo el polinomio de Rijndael (0x11B)
local function gmul(a, b)
    local p = 0
    for _ = 1, 8 do
        if (b & 1) == 1 then p = p ~ a end
        local hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi ~= 0 then a = a ~ 0x1B end
        b = b >> 1
    end
    return p
end

-- Expansión de clave para AES-128: produce 44 palabras de 4 bytes (11 round keys)
-- w[0..43], cada w[i] = {b1,b2,b3,b4}
local function key_expansion(key)
    assert(#key == 16, "la clave AES-128 debe tener exactamente 16 bytes, tiene " .. #key)
    local w = {}
    for i = 0, 3 do
        w[i] = {
            string.byte(key, i * 4 + 1),
            string.byte(key, i * 4 + 2),
            string.byte(key, i * 4 + 3),
            string.byte(key, i * 4 + 4),
        }
    end

    for i = 4, 43 do
        local temp = { w[i - 1][1], w[i - 1][2], w[i - 1][3], w[i - 1][4] }
        if i % 4 == 0 then
            temp = { temp[2], temp[3], temp[4], temp[1] } -- RotWord
            for k = 1, 4 do temp[k] = SBOX[temp[k] + 1] end -- SubWord
            temp[1] = temp[1] ~ RCON[i / 4]
        end
        w[i] = {
            w[i - 4][1] ~ temp[1],
            w[i - 4][2] ~ temp[2],
            w[i - 4][3] ~ temp[3],
            w[i - 4][4] ~ temp[4],
        }
    end
    return w
end

local function add_round_key(state, w, round)
    for c = 0, 3 do
        local word = w[round * 4 + c]
        for r = 1, 4 do
            local idx = c * 4 + r
            state[idx] = state[idx] ~ word[r]
        end
    end
end

local function sub_bytes(state)
    for i = 1, 16 do state[i] = SBOX[state[i] + 1] end
end

local function inv_sub_bytes(state)
    for i = 1, 16 do state[i] = INV_SBOX[state[i] + 1] end
end

-- Fila r (0-3, r=0 sin cambios): bytes en columnas 0,1,2,3 -> índices r+1, r+5, r+9, r+13
local function shift_rows(state)
    for r = 1, 3 do
        local idx = { r + 1, r + 5, r + 9, r + 13 }
        local vals = { state[idx[1]], state[idx[2]], state[idx[3]], state[idx[4]] }
        for k = 1, 4 do
            state[idx[k]] = vals[((k - 1 + r) % 4) + 1]
        end
    end
end

local function inv_shift_rows(state)
    for r = 1, 3 do
        local idx = { r + 1, r + 5, r + 9, r + 13 }
        local vals = { state[idx[1]], state[idx[2]], state[idx[3]], state[idx[4]] }
        for k = 1, 4 do
            state[idx[k]] = vals[((k - 1 - r) % 4) + 1]
        end
    end
end

local function mix_columns(state)
    for c = 0, 3 do
        local i = c * 4
        local a0, a1, a2, a3 = state[i+1], state[i+2], state[i+3], state[i+4]
        state[i+1] = gmul(a0,2) ~ gmul(a1,3) ~ a2 ~ a3
        state[i+2] = a0 ~ gmul(a1,2) ~ gmul(a2,3) ~ a3
        state[i+3] = a0 ~ a1 ~ gmul(a2,2) ~ gmul(a3,3)
        state[i+4] = gmul(a0,3) ~ a1 ~ a2 ~ gmul(a3,2)
    end
end

local function inv_mix_columns(state)
    for c = 0, 3 do
        local i = c * 4
        local a0, a1, a2, a3 = state[i+1], state[i+2], state[i+3], state[i+4]
        state[i+1] = gmul(a0,14) ~ gmul(a1,11) ~ gmul(a2,13) ~ gmul(a3,9)
        state[i+2] = gmul(a0,9) ~ gmul(a1,14) ~ gmul(a2,11) ~ gmul(a3,13)
        state[i+3] = gmul(a0,13) ~ gmul(a1,9) ~ gmul(a2,14) ~ gmul(a3,11)
        state[i+4] = gmul(a0,11) ~ gmul(a1,13) ~ gmul(a2,9) ~ gmul(a3,14)
    end
end

local function encrypt_block(input, w)
    local state = {}
    for i = 1, 16 do state[i] = string.byte(input, i) end

    add_round_key(state, w, 0)
    for round = 1, 9 do
        sub_bytes(state)
        shift_rows(state)
        mix_columns(state)
        add_round_key(state, w, round)
    end
    sub_bytes(state)
    shift_rows(state)
    add_round_key(state, w, 10)

    local out = {}
    for i = 1, 16 do out[i] = string.char(state[i]) end
    return table.concat(out)
end

local function decrypt_block(input, w)
    local state = {}
    for i = 1, 16 do state[i] = string.byte(input, i) end

    add_round_key(state, w, 10)
    for round = 9, 1, -1 do
        inv_shift_rows(state)
        inv_sub_bytes(state)
        add_round_key(state, w, round)
        inv_mix_columns(state)
    end
    inv_shift_rows(state)
    inv_sub_bytes(state)
    add_round_key(state, w, 0)

    local out = {}
    for i = 1, 16 do out[i] = string.char(state[i]) end
    return table.concat(out)
end

-- data debe venir alineado a 16 bytes (PKCS7 ya aplicado por quien llame)
function aes128.encrypt_ecb(key, data)
    assert(#data % 16 == 0, "los datos deben estar alineados a 16 bytes")
    local w = key_expansion(key)
    local blocks = {}
    for i = 1, #data, 16 do
        blocks[#blocks + 1] = encrypt_block(string.sub(data, i, i + 15), w)
    end
    return table.concat(blocks)
end

function aes128.decrypt_ecb(key, data)
    assert(#data % 16 == 0, "los datos cifrados deben ser múltiplo de 16 bytes")
    local w = key_expansion(key)
    local blocks = {}
    for i = 1, #data, 16 do
        blocks[#blocks + 1] = decrypt_block(string.sub(data, i, i + 15), w)
    end
    return table.concat(blocks)
end

-- Primitivas de bloque crudo, expuestas para que gcm.lua las reutilice
-- (GCM solo necesita cifrar bloques individuales de 16 bytes, nunca
-- padding/ECB de mensaje completo).
function aes128.expand_key(key)
    return key_expansion(key)
end

function aes128.encrypt_block_raw(block16bytes, expanded_key)
    assert(#block16bytes == 16, "encrypt_block_raw espera exactamente 16 bytes")
    return encrypt_block(block16bytes, expanded_key)
end

-- Vector de prueba oficial FIPS-197 Appendix B. Corre esto una vez desde
-- una consola Lua (fuera del hub) para confirmar que la implementación es
-- correcta antes de fiarte de ella con datos reales del termostato.
function aes128.test_vector()
    local key = string.char(0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f)
    local plaintext = string.char(0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff)
    local expected = "69c4e0d86a7b0430d8cdb78070b4c55a"

    local cipher = aes128.encrypt_ecb(key, plaintext)
    local hex = {}
    for i = 1, #cipher do hex[i] = string.format("%02x", string.byte(cipher, i)) end
    local got = table.concat(hex)

    local decrypted = aes128.decrypt_ecb(key, cipher)

    return {
        ok = (got == expected) and (decrypted == plaintext),
        expected = expected,
        got = got,
    }
end

